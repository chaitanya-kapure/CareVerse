/**
 * Toggles the colour theme. The icon shows the theme the button switches *to*,
 * and `aria-pressed` reports whether dark mode is currently on, so the state is
 * available to screen-reader users and not carried by colour alone.
 */
export default function ThemeToggle({ className = "" }: { className?: string }) {
  const { theme, toggleTheme } = useTheme();
  const isDark = theme === "dark";

  return (
    <button
      type="button"
      onClick={toggleTheme}
      aria-pressed={isDark}
      aria-label={isDark ? "Switch to light mode" : "Switch to dark mode"}
      title={isDark ? "Switch to light mode" : "Switch to dark mode"}
      className={`inline-flex h-9 w-9 items-center justify-center rounded-md border border-slate-300
        bg-white text-slate-600 transition-colors hover:bg-slate-50 hover:text-slate-900
        focus-visible:outline focus-visible:outline-2 focus-visible:outline-offset-2
        focus-visible:outline-teal-700 ${className}`}
    >
      {isDark ? <SunIcon /> : <MoonIcon />}
    </button>
  );
}