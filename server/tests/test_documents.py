def test_deleting_removes_both_the_row_and_the_file(
    client, patient, storage, db
):
    created = upload_file(client, patient["headers"], text_pdf(LAB_REPORT)).json()
    document = stored_documents(db, patient["id"])[0]
    assert storage.exists(document["storage_key"])

    response = client.delete(
        f"/patients/me/documents/{created['id']}", headers=patient["headers"]
    )

    assert response.status_code == 200, response.text
    assert response.json()["code"] == "DOCUMENT_DELETED"

    assert db.medical_documents.find_one({"_id": ObjectId(created["id"])}) is None
    assert not storage.exists(document["storage_key"])
    assert client.get("/patients/me/documents", headers=patient["headers"]).json()[
        "total"
    ] == 0


def test_deleting_twice_is_a_404_not_a_crash(client, patient, storage):
    created = upload_file(client, patient["headers"], text_pdf()).json()

    first = client.delete(
        f"/patients/me/documents/{created['id']}", headers=patient["headers"]
    )
    second = client.delete(
        f"/patients/me/documents/{created['id']}", headers=patient["headers"]
    )

    assert first.status_code == 200
    assert second.status_code == 404
    assert second.json()["code"] == "DOCUMENT_NOT_FOUND"


