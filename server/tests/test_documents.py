def test_a_file_that_is_not_a_pdf_is_refused_by_type(client, patient, db):
    response = upload_file(
        client, patient["headers"], b"Dear doctor, see attached", filename="notes.txt",
        mime="text/plain",
    )

    assert response.status_code == 415, response.text
    assert response.json()["code"] == "UNSUPPORTED_FILE_TYPE"
    assert stored_documents(db, patient["id"]) == []
    assert client.get("/patients/me/documents", headers=patient["headers"]).json()[
        "total"
    ] == 0


def test_a_file_that_lies_about_its_type_is_refused_by_content(client, patient, db):
    """The MIME type and the extension are both asserted by the client.

    This one claims `application/pdf` and is called `.pdf`, and still must
    not be accepted -- the magic bytes are the check that decides."""
    response = upload_file(
        client, patient["headers"], b"this is not actually a pdf", filename="report.pdf"
    )

    assert response.status_code == 400, response.text
    assert response.json()["code"] == "INVALID_FILE_TYPE"
    assert stored_documents(db, patient["id"]) == []


def test_an_oversized_file_is_refused(client, patient, db):
    response = upload_file(
        client, patient["headers"], oversized_pdf(), filename="huge.pdf"
    )

    assert response.status_code == 413, response.text
    assert response.json()["code"] == "FILE_TOO_LARGE"
    assert f"{settings.max_upload_mb} MB" in response.json()["detail"]
    # Nothing was written, no matter how far the stream got.
    assert stored_documents(db, patient["id"]) == []


