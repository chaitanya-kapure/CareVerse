"""The PDF document pipeline, end to end through the HTTP API.

Covers the required cases: upload, invalid file rejection, successful
extraction, extraction failure, own-document access, cross-patient access
denied, deletion, and a missing document.

Everything here goes through `/patients/me/documents`, which is also the
point: there is no patient id anywhere in these paths, so the only id a test
can tamper with is the document id -- and tampering with it is exactly what
`test_cross_patient_cannot_...` exercises.
"""

from bson import ObjectId

from app.config import settings
from tests.pdf_fixtures import blank_pdf, corrupt_pdf, oversized_pdf, text_pdf

LAB_REPORT = "Complete Blood Count\nHaemoglobin 14.2 g/dL\nPlatelets 250000 /uL"


def upload_file(client, headers, content, filename="report.pdf", mime="application/pdf", **fields):
    """POST a multipart upload the way the browser does."""
    return client.post(
        "/patients/me/documents",
        files={"file": (filename, content, mime)},
        data=fields,
        headers=headers,
    )


def stored_documents(db, patient_id):
    return list(db.medical_documents.find({"patient_id": patient_id}))


# =====================================================================
# upload + successful extraction
# =====================================================================


def test_upload_stores_the_file_and_extracts_its_text(client, patient, storage, db):
    content = text_pdf(LAB_REPORT)

    response = upload_file(
        client, patient["headers"],
        content,
        filename="cbc.pdf",
        title="CBC report",
        category="lab_report",
        document_date="2026-06-01",
    )

    assert response.status_code == 201, response.text
    body = response.json()

    # Metadata required by the spec.
    assert body["patient_id"] == patient["id"]
    assert body["original_filename"] == "cbc.pdf"
    assert body["title"] == "CBC report"
    assert body["category"] == "lab_report"
    assert body["document_date"] == "2026-06-01"
    assert body["mime_type"] == "application/pdf"
    assert body["size_bytes"] == len(content)
    assert body["uploaded_at"]

    # Extraction really ran, on the real bytes.
    assert body["extraction_status"] == "completed"
    assert body["page_count"] == 1
    assert "Haemoglobin 14.2 g/dL" in body["extracted_text"]
    assert body["character_count"] == len(body["extracted_text"])
    assert body["has_text"] is True
    assert body["extraction_error"] is None

    # ...and the file is on disk, under a name we generated.
    document = stored_documents(db, patient["id"])[0]
    assert storage.exists(document["storage_key"])
    assert storage.open(document["storage_key"]) == content


def test_the_stored_name_is_generated_never_taken_from_the_upload(
    client, patient, storage, db
):
    """A filename is attacker-controlled input. It must never decide where
    bytes land, and it must not survive as a path."""
    hostile = "../../etc/passwd.pdf"

    response = upload_file(client, patient["headers"], text_pdf(), filename=hostile)

    assert response.status_code == 201, response.text
    body = response.json()

    # Displayed to the human, reduced to its basename: every directory
    # component is dropped rather than escaped.
    assert body["original_filename"] == "passwd.pdf"

    document = stored_documents(db, patient["id"])[0]
    # The key is generated by us: flat, opaque, no separators.
    assert ".." not in document["storage_key"]
    assert "/" not in document["storage_key"]
    assert document["storage_key"] != hostile
    assert storage.exists(document["storage_key"])


def test_title_falls_back_to_the_filename_when_not_supplied(client, patient, storage):
    response = upload_file(
        client, patient["headers"], text_pdf(), filename="lipid_panel_june.pdf"
    )

    assert response.status_code == 201, response.text
    assert response.json()["title"] == "Lipid panel june"


def test_uploaded_files_are_listed_newest_first(client, patient, storage):
    first = upload_file(client, patient["headers"], text_pdf(), filename="older.pdf")
    second = upload_file(client, patient["headers"], text_pdf(), filename="newer.pdf")
    assert first.status_code == 201 and second.status_code == 201

    response = client.get("/patients/me/documents", headers=patient["headers"])

    assert response.status_code == 200, response.text
    body = response.json()
    assert body["total"] == 2
    assert {item["id"] for item in body["items"]} == {
        first.json()["id"],
        second.json()["id"],
    }
    times = [item["uploaded_at"] for item in body["items"]]
    assert times == sorted(times, reverse=True)

    # Lists are metadata: resending every document's text on each poll would
    # dominate the response.
    assert all("extracted_text" not in item for item in body["items"])


def test_an_empty_record_list_is_not_an_error(client, patient, storage):
    response = client.get("/patients/me/documents", headers=patient["headers"])

    assert response.status_code == 200, response.text
    assert response.json() == {"items": [], "total": 0}


