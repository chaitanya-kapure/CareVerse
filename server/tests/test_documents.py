def test_an_upload_requires_a_token(client, db):
    response = client.post(
        "/patients/me/documents",
        files={"file": ("report.pdf", text_pdf(), "application/pdf")},
    )

    assert response.status_code == 401, response.text
    assert db.medical_documents.count_documents({}) == 0


def test_a_doctor_cannot_use_the_patient_document_routes(client, doctor, storage):
    """Being a doctor is not authorization. Nothing in this phase shares a
    record with a doctor; that needs an explicit grant, which is Phase 3."""
    listing = client.get("/patients/me/documents", headers=doctor["headers"])
    upload_attempt = upload_file(client, doctor["headers"], text_pdf())

    for response in (listing, upload_attempt):
        assert response.status_code == 403, response.text
        assert response.json()["code"] == "ROLE_NOT_ALLOWED"


def test_a_token_from_a_deleted_account_is_refused(
    client, patient, storage, db
):
    upload_file(client, patient["headers"], text_pdf())
    db.users.delete_one({"_id": ObjectId(patient["id"])})

    response = client.get("/patients/me/documents", headers=patient["headers"])

    assert response.status_code == 401
    assert response.json()["code"] == "USER_NOT_FOUND"
