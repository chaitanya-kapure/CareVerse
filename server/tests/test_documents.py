def test_a_patient_can_open_their_own_document(client, patient, storage):
    created = upload_file(
        client, patient["headers"], text_pdf(LAB_REPORT), filename="cbc.pdf"
    ).json()

    response = client.get(
        f"/patients/me/documents/{created['id']}", headers=patient["headers"]
    )

    assert response.status_code == 200, response.text
    body = response.json()
    assert body["id"] == created["id"]
    assert body["extraction_status"] == "completed"
    assert "Haemoglobin 14.2 g/dL" in body["extracted_text"]

    # Phase 4A. This used to assert `extracted_data == {}`, which recorded the
    # pre-Phase-4A state rather than a property worth keeping: the structured
    # pass is the point of this phase, so that assertion could only have held
    # if the feature did nothing. It is replaced with a stronger one that
    # pins the actual lab values, their units, and their source attribution --
    # and, just as importantly, pins the absence of a `flag`, because nothing
    # on this report marks any value as abnormal and the extractor must not
    # decide that for itself.
    extracted = body["extracted_data"]
    assert extracted["lab_values"] == [
        {
            "name": "Haemoglobin",
            "value": "14.2",
            "unit": "g/dL",
            "source_text": "Haemoglobin 14.2 g/dL",
        },
        {
            "name": "Platelets",
            "value": "250000",
            "unit": "/uL",
            "source_text": "Platelets 250000 /uL",
        },
    ]
    # No condition, finding, medication, or metadata was printed on this
    # report, so none may appear.
    for absent in (
        "stated_conditions",
        "abnormal_findings",
        "medications",
        "report_title",
        "document_date",
        "referring_facility",
        "referring_doctor",
    ):
        assert absent not in extracted, f"{absent} was not stated on this report"


def test_the_original_file_streams_back_byte_for_byte(client, patient, storage, db):
    content = text_pdf(LAB_REPORT)
    created = upload_file(client, patient["headers"], content, filename="cbc.pdf").json()

    response = client.get(
        f"/patients/me/documents/{created['id']}/file", headers=patient["headers"]
    )

    assert response.status_code == 200, response.text
    assert response.headers["content-type"].startswith("application/pdf")
    assert response.content == content
    # Never cached off the device: this is the record itself.
    assert "no-store" in response.headers["cache-control"]
    assert "attachment" not in response.headers["content-disposition"]


def test_a_missing_document_returns_404(client, patient, storage):
    # A well-formed id that simply does not exist.
    absent = "64b000000000000000000000"

    detail = client.get(
        f"/patients/me/documents/{absent}", headers=patient["headers"]
    )
    download = client.get(
        f"/patients/me/documents/{absent}/file", headers=patient["headers"]
    )
    removal = client.delete(
        f"/patients/me/documents/{absent}", headers=patient["headers"]
    )

    for response in (detail, download, removal):
        assert response.status_code == 404, response.text
        assert response.json()["code"] == "DOCUMENT_NOT_FOUND"


def test_a_malformed_document_id_returns_404_not_a_500(client, patient, storage):
    # Neither of these is a valid ObjectId, so neither can reach Mongo as a
    # failed cast -- the service rejects them before the query runs.
    for bad in ("not-an-id", "zzzzzzzzzzzzzzzzzzzzzzzzzz"):
        response = client.get(
            f"/patients/me/documents/{bad}", headers=patient["headers"]
        )
        assert response.status_code == 404, (bad, response.text)
        assert response.json()["code"] == "DOCUMENT_NOT_FOUND"


