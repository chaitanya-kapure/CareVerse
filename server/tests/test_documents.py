def test_a_scanned_pdf_is_marked_as_needing_ocr_not_as_empty(
    client, patient, storage, db
):
    """The image-only case.

    The document opens and every page reads fine; there is simply no embedded
    text. The honest answer is a status saying so, with *no* text -- an empty
    string here would let a later screen present "this record says nothing"
    as a finding."""
    response = upload_file(client, patient["headers"], blank_pdf(), filename="scan.pdf")

    assert response.status_code == 201, response.text
    body = response.json()
    assert body["extraction_status"] == "needs_ocr"
    assert body["extracted_text"] is None
    assert body["character_count"] == 0
    assert body["has_text"] is False
    assert body["extraction_error"] is None
    assert body["page_count"] == 1

    # The file itself is untouched and still listed.
    detail = client.get(
        f"/patients/me/documents/{body['id']}", headers=patient["headers"]
    )
    assert detail.status_code == 200
    assert detail.json()["extraction_status"] == "needs_ocr"
    assert storage.exists(stored_documents(db, patient["id"])[0]["storage_key"])


def test_an_unreadable_pdf_fails_extraction_without_failing_the_upload(
    client, patient, storage, db
):
    """Extraction is the only step that parses untrusted content, and the one
    most likely to throw. It runs *after* the row exists precisely so this
    degrades the document instead of losing it."""
    response = upload_file(client, patient["headers"], corrupt_pdf(), filename="broken.pdf")

    assert response.status_code == 201, response.text
    body = response.json()
    assert body["extraction_status"] == "failed"
    assert body["extracted_text"] is None
    assert body["has_text"] is False
    # A sentence the patient can read, not a stack trace or pypdf internals.
    assert body["extraction_error"] == "The file could not be read as a PDF."
    assert "Traceback" not in body["extraction_error"]

    # The document survives: listed, openable, downloadable.
    document = stored_documents(db, patient["id"])[0]
    assert storage.exists(document["storage_key"])
    listing = client.get("/patients/me/documents", headers=patient["headers"])
    assert listing.json()["total"] == 1
    download = client.get(
        f"/patients/me/documents/{body['id']}/file", headers=patient["headers"]
    )
    assert download.status_code == 200
    assert download.content == corrupt_pdf()


