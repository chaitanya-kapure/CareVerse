def test_another_patient_cannot_read_your_document(
    client, patient, other_patient, storage
):
    """Change the id in the request and nothing happens.

    404 rather than 403, deliberately: 403 would confirm that a document with
    that id exists, turning this endpoint into an oracle for guessing other
    patients' document ids."""
    created = upload_file(client, patient["headers"], text_pdf(LAB_REPORT)).json()

    response = client.get(
        f"/patients/me/documents/{created['id']}", headers=other_patient["headers"]
    )

    assert response.status_code == 404, response.text
    assert response.json()["code"] == "DOCUMENT_NOT_FOUND"
    # ...and no detail from the real document leaks through.
    assert "Haemoglobin" not in response.text


def test_another_patient_cannot_download_your_file(
    client, patient, other_patient, storage
):
    created = upload_file(client, patient["headers"], text_pdf(LAB_REPORT)).json()

    response = client.get(
        f"/patients/me/documents/{created['id']}/file",
        headers=other_patient["headers"],
    )

    assert response.status_code == 404, response.text
    assert response.content != text_pdf(LAB_REPORT)


def test_another_patient_cannot_delete_your_document(
    client, patient, other_patient, storage, db
):
    created = upload_file(client, patient["headers"], text_pdf(LAB_REPORT)).json()

    response = client.delete(
        f"/patients/me/documents/{created['id']}", headers=other_patient["headers"]
    )

    assert response.status_code == 404, response.text

    # Neither the row nor the file was touched.
    assert client.get(
        f"/patients/me/documents/{created['id']}", headers=patient["headers"]
    ).status_code == 200
    document = stored_documents(db, patient["id"])[0]
    assert storage.exists(document["storage_key"])


def test_each_patient_sees_only_their_own_list(
    client, patient, other_patient, storage
):
    mine = upload_file(client, patient["headers"], text_pdf(), filename="mine.pdf").json()
    theirs = upload_file(
        client, other_patient["headers"], text_pdf(), filename="theirs.pdf"
    ).json()

    my_list = client.get("/patients/me/documents", headers=patient["headers"]).json()
    their_list = client.get(
        "/patients/me/documents", headers=other_patient["headers"]
    ).json()

    assert [item["id"] for item in my_list["items"]] == [mine["id"]]
    assert [item["id"] for item in their_list["items"]] == [theirs["id"]]
    assert my_list["items"][0]["patient_id"] == patient["id"]
    assert their_list["items"][0]["patient_id"] == other_patient["id"]


def test_tampering_with_the_patient_id_field_changes_nothing(
    client, patient, other_patient, storage, db
):
    """Even a document row's own `patient_id` is not something a caller can
    steer: every read is scoped by the id taken from the token, so the field
    in the request is never consulted."""
    created = upload_file(client, patient["headers"], text_pdf(), filename="mine.pdf").json()

    # Rewrite the stored document to claim the other patient owns it.
    db.medical_documents.update_one(
        {"_id": ObjectId(created["id"])},
        {"$set": {"patient_id": other_patient["id"]}},
    )

    # The original owner can no longer see it...
    assert (
        client.get(
            f"/patients/me/documents/{created['id']}", headers=patient["headers"]
        ).status_code
        == 404
    )
    # ...and the person it now claims to belong to can, because ownership is
    # read from the row and compared against the token -- not from anything
    # in the request body.
    assert (
        client.get(
            f"/patients/me/documents/{created['id']}",
            headers=other_patient["headers"],
        ).status_code
        == 200
    )


